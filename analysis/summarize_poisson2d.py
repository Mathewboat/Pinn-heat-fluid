# summarize_poisson2d.py
# Builds the 2D Poisson tables and figure from the raw per-run JSON files.
# Put it in analysis/ and run from anywhere:
#     python analysis/summarize_poisson2d.py
#
# Reads    results/kaggle/poisson2d_*/*.json            (top level of every poisson2d_* folder)
#          results/baselines/classical_baselines.json   (classical direct-solve reference)
# Writes   results/tables/poisson2d_experiments.md
#          results/figures/poisson2d_recipe.png
#
# IMPORTANT: the stored "linf" is an absolute error in units of u = SCALE * T, so it is NOT comparable
# between the raw and rescaled settings. This script converts it to a relative L-infinity error
# (divided by the exact peak of u). L2, flux and heat errors are already relative.
#
# Needs numpy, scipy, matplotlib.

import glob
import json
from collections import defaultdict
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
from scipy.stats import mannwhitneyu

ROOT = Path(__file__).resolve().parents[1]
PEAK_RAW = 1 / (2 * np.pi**2)                      # exact peak of T
rows = []
for f in sorted(glob.glob(str(ROOT / "results" / "kaggle" / "poisson2d_*" / "*.json"))):
    d = json.load(open(f))
    d.setdefault("bc_weight", 1.0)
    peak = 1.0 if d["scale"] == "rescaled" else PEAK_RAW
    d["final"]["linf_rel"] = d["final"]["linf"] / peak
    rows.append(d)
if not rows:
    raise SystemExit("No 2D Poisson JSON files found under results/kaggle/poisson2d_*/")

lines = []


def out(s=""):
    print(s)
    lines.append(s)


def key(r):
    return (r["precision"], r["constraint"], r["scale"], r["bc_weight"])


def label(k):
    prec, con, sc, w = k
    p = {"float32": "f32", "float64": "f64"}.get(prec, prec)
    c = "hard" if con == "hard" else (f"soft w={w:g}" if w != 1 else "soft")
    return f"{p} {c} {sc}"


groups = defaultdict(list)
for r in rows:
    groups[key(r)].append(r)
order = sorted(groups, key=lambda k: (k[0], k[1] == "hard", k[2] == "rescaled", k[3]))
vals = lambda k, m: np.array([r["final"][m] for r in groups[k]])


def fmt(v):
    return f"{np.median(v):.2e} [{np.min(v):.2e}, {np.max(v):.2e}]"


out("## 2D Poisson experiments summary (generated by analysis/summarize_poisson2d.py)")
out(f"\n{len(rows)} runs. u = SCALE*T; 'raw' SCALE = 1, 'rescaled' SCALE = 2 pi^2. "
    "All errors relative to the exact solution; rel. Linf = Linf / exact peak.\n")
out("| setting | n | L2 median [min, max] | rel. Linf (median) | wall-flux L2 (median) | total-heat error (median) | "
    "L-BFGS its (median) | stopped before cap | min/run |")
out("|---|---|---|---|---|---|---|---|---|")
for k in order:
    rs = groups[k]
    its = int(np.median([r["lbfgs_iters_run"] for r in rs]))
    mins = np.mean([(r["seconds_adam"] + r["seconds_lbfgs"]) / 60 for r in rs])
    out(f"| {label(k)} | {len(rs)} | {fmt(vals(k, 'l2'))} | {np.median(vals(k, 'linf_rel')):.2e} | "
        f"{np.median(vals(k, 'flux_l2')):.2e} | {np.median(vals(k, 'heat_total_err')):.2e} | {its} | "
        f"{sum(r['lbfgs_stopped_early'] for r in rs)}/{len(rs)} | {mins:.1f} |")

# ---- pairwise comparisons (float32) ----
F = "float32"
pairs = [((F, "soft", "raw", 1.0), (F, "hard", "raw", 1.0)),
         ((F, "soft", "rescaled", 1.0), (F, "hard", "rescaled", 1.0)),
         ((F, "soft", "raw", 1.0), (F, "soft", "rescaled", 1.0)),
         ((F, "hard", "raw", 1.0), (F, "hard", "rescaled", 1.0))]
out("\n### Pairwise comparisons (float32). ratio = first median / second median; 'separated' = every run of the better "
    "setting beats every run of the other; p = exact two-sided Mann-Whitney\n")
out("| first | second | metric | ratio of medians | separated? | p |")
out("|---|---|---|---|---|---|")
for a, b in pairs:
    if a not in groups or b not in groups:
        continue
    for m, nice in (("l2", "L2"), ("linf_rel", "rel. Linf"), ("flux_l2", "wall-flux L2"), ("heat_total_err", "total-heat error")):
        x, y = vals(a, m), vals(b, m)
        p = mannwhitneyu(x, y, alternative="two-sided", method="exact").pvalue
        sep = "yes" if (x.max() < y.min() or y.max() < x.min()) else "no"
        out(f"| {label(a)} | {label(b)} | {nice} | {np.median(x) / np.median(y):.2f}x | {sep} | {p:.1e} |")
out("\nWith 10 vs 10 runs the smallest possible p is 1.1e-5. Several comparisons are made; read p as a rank statement.")

# ---- classical reference ----
fd = None
fd_path = ROOT / "results" / "baselines" / "classical_baselines.json"
if fd_path.exists():
    fd = json.load(open(fd_path)).get("poisson2d_direct")
    if fd:
        out("\n### Classical second-order finite differences, direct sparse solve (results/baselines)\n")
        out("| grid points | L2 | seconds |")
        out("|---|---|---|")
        for r in fd:
            out(f"| {r['points']:,} | {r['l2']:.2e} | {r['seconds']:.3f} |")

# ---- figure ----
fig, axes = plt.subplots(1, 2, figsize=(13, 5))
rng = np.random.default_rng(0)
for ax, m, title in ((axes[0], "l2", "field relative L2"), (axes[1], "flux_l2", "wall heat-flux relative L2")):
    for i, k in enumerate(order):
        v = vals(k, m)
        ax.scatter(i + rng.uniform(-0.12, 0.12, len(v)), v, s=36, alpha=0.8, zorder=3)
        ax.hlines(np.median(v), i - 0.3, i + 0.3, colors="k", lw=2, zorder=4)
    if fd and m == "l2":
        for r, ls in zip(fd[2:], (":", "--")):
            ax.axhline(r["l2"], color="gray", ls=ls, lw=1,
                       label=f"classical FD, {r['points']:,} pts ({r['seconds']:.2f} s)")
        ax.legend(fontsize=8, loc="upper right")
    ax.set_yscale("log")
    ax.set_xticks(range(len(order)))
    ax.set_xticklabels([label(k).replace(" ", "\n", 1) for k in order], fontsize=8)
    ax.set_title(title)
    ax.grid(True, which="both", axis="y", alpha=0.3)
axes[0].set_ylabel("error vs exact solution")
fig.suptitle("2D Poisson PINN: every run (dots) and median (bar)")
fig.tight_layout()
(ROOT / "results" / "figures").mkdir(parents=True, exist_ok=True)
fig.savefig(ROOT / "results" / "figures" / "poisson2d_recipe.png", dpi=150)
(ROOT / "results" / "tables").mkdir(parents=True, exist_ok=True)
(ROOT / "results" / "tables" / "poisson2d_experiments.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
print("\nSaved results/figures/poisson2d_recipe.png and results/tables/poisson2d_experiments.md")
