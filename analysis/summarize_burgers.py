# summarize_burgers.py
# Builds the Burgers experiment tables and figure from the raw per-run JSON files.
# Put it in analysis/ and run from anywhere:
#     python analysis/summarize_burgers.py
#
# Reads    results/kaggle/burgers_*/*.json            (top level of every burgers_* folder)
#          results/baselines/classical_baselines.json  (classical finite-difference reference)
# Writes   results/tables/burgers_experiments.md
#          results/figures/burgers_recipe.png
#
# Needs numpy, scipy, matplotlib.

import glob
import json
from collections import defaultdict
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
from scipy.stats import mannwhitneyu

ROOT = Path(__file__).resolve().parents[1]
rows = []
for f in sorted(glob.glob(str(ROOT / "results" / "kaggle" / "burgers_*" / "*.json"))):
    d = json.load(open(f))
    d.setdefault("bc_weight", 1.0)
    d.setdefault("resample", False)
    rows.append(d)
if not rows:
    raise SystemExit("No Burgers JSON files found under results/kaggle/burgers_*/")

lines = []


def out(s=""):
    print(s)
    lines.append(s)


def key(r):
    return (r["precision"], r["constraint"], r["bc_weight"], bool(r["resample"]))


def label(k):
    prec, con, w, rs = k
    base = "hard" if con == "hard" else f"soft w={w:g}"
    return f"{ {'float32': 'f32', 'float64': 'f64'}.get(prec, prec) } {base}" + (" +resample" if rs else "")


groups = defaultdict(list)
for r in rows:
    groups[key(r)].append(r)
order = sorted(groups, key=lambda k: (k[0], k[1] == "hard", k[3], k[2]))


def fmt(v):
    return f"{np.median(v):.2e} [{np.min(v):.2e}, {np.max(v):.2e}]"


out("## Burgers experiments summary (generated by analysis/summarize_burgers.py)")
out(f"\n{len(rows)} runs. Metrics are on the 256 x 100 reference grid; near-shock = |x| <= 0.15, t >= 0.35.\n")
out("| setting | n | L2 median [min, max] | near-shock L2 median [min, max] | Linf median [min, max] | "
    "L-BFGS its (median) | stopped before cap | min/run |")
out("|---|---|---|---|---|---|---|---|")
for k in order:
    rs = groups[k]
    g = lambda m: np.array([r["final"][m] for r in rs])
    its = int(np.median([r["lbfgs_iters_run"] for r in rs]))
    mins = np.mean([(r["seconds_adam"] + r["seconds_lbfgs"]) / 60 for r in rs])
    out(f"| {label(k)} | {len(rs)} | {fmt(g('l2'))} | {fmt(g('l2_near_shock'))} | {fmt(g('linf'))} | "
        f"{its} | {sum(r['lbfgs_stopped_early'] for r in rs)}/{len(rs)} | {mins:.1f} |")

# ---- comparisons against the float32 soft w=1 reference group (if present) ----
ref_key = ("float32", "soft", 1.0, False)
if ref_key in groups:
    out("\n### Each setting vs float32 soft w=1 (exact two-sided Mann-Whitney p; ratio = reference median / setting median)\n")
    out("| setting | metric | ratio of medians | worst run of setting vs best run of reference | p |")
    out("|---|---|---|---|---|")
    for k in order:
        if k == ref_key:
            continue
        for m, nice in (("l2", "L2"), ("l2_near_shock", "near-shock L2"), ("linf", "Linf")):
            a = np.array([r["final"][m] for r in groups[ref_key]])
            b = np.array([r["final"][m] for r in groups[k]])
            if len(a) < 3 or len(b) < 3:
                continue
            p = mannwhitneyu(a, b, alternative="two-sided", method="exact").pvalue
            out(f"| {label(k)} | {nice} | {np.median(a) / np.median(b):.2f}x | "
                f"{b.max() / a.min():.2f} | {p:.4f} |")
    out("\n'worst/best' below 1 means every run of the setting beat every reference run. With 5 vs 5 the smallest "
        "possible p is 0.0079; several comparisons are made, so read p as a rank statement only.")

# ---- classical reference ----
fd = None
fd_path = ROOT / "results" / "baselines" / "classical_baselines.json"
if fd_path.exists():
    fd = json.load(open(fd_path)).get("burgers_central_fd_bdf")
    if fd:
        out("\n### Classical central finite differences + BDF (same metrics, from results/baselines)\n")
        out("| grid points | L2 | near-shock L2 | seconds |")
        out("|---|---|---|---|")
        for r in fd:
            out(f"| {r['grid_points']:,} | {r['l2']:.2e} | {r['l2_near_shock']:.2e} | {r['seconds']:.2f} |")

# ---- figure ----
fig, axes = plt.subplots(1, 2, figsize=(13, 5), sharey=False)
rng = np.random.default_rng(0)
for ax, m, title in ((axes[0], "l2", "whole-grid relative L2"), (axes[1], "l2_near_shock", "near-shock relative L2")):
    for i, k in enumerate(order):
        v = np.array([r["final"][m] for r in groups[k]])
        ax.scatter(i + rng.uniform(-0.12, 0.12, len(v)), v, s=40, alpha=0.8, zorder=3)
        ax.hlines(np.median(v), i - 0.3, i + 0.3, colors="k", lw=2, zorder=4)
    if fd:
        for r, ls in zip(fd[1:], (":", "--", "-.")):
            ax.axhline(r[m], color="gray", ls=ls, lw=1, label=f"classical FD, {r['grid_points']:,} pts ({r['seconds']:.2f} s)")
    ax.set_yscale("log")
    ax.set_xticks(range(len(order)))
    ax.set_xticklabels([label(k).replace(" ", "\n", 1) for k in order], fontsize=9)
    ax.set_title(title)
    ax.grid(True, which="both", axis="y", alpha=0.3)
axes[0].set_ylabel("error vs reference solution")
axes[1].legend(fontsize=8, loc="upper right")
fig.suptitle("Burgers PINN: every run (dots) and median (bar); grey lines = classical finite-difference solver")
fig.tight_layout()
(ROOT / "results" / "figures").mkdir(parents=True, exist_ok=True)
fig.savefig(ROOT / "results" / "figures" / "burgers_recipe.png", dpi=150)
(ROOT / "results" / "tables").mkdir(parents=True, exist_ok=True)
(ROOT / "results" / "tables" / "burgers_experiments.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
print("\nSaved results/figures/burgers_recipe.png and results/tables/burgers_experiments.md")
