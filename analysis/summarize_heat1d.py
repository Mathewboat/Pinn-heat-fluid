# summarize_heat1d.py
# Builds the Experiment 1 tables and figure directly from the raw per-run JSON files,
# so nothing is transcribed by hand.  Put it in analysis/ and run from anywhere:
#     python analysis/summarize_heat1d.py
#
# Reads    results/kaggle/heat1d_recipe/*.json    Experiment 1a (initialization NOT seeded)
#          results/kaggle/heat1d_weights/*.json   Experiment 1b (seeded initialization, reproducible)
# Writes   results/tables/heat1d_experiments.md
#          results/figures/heat1d_recipe_l2.png
#
# Needs numpy, scipy, matplotlib.

import glob
import json
from collections import defaultdict
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
from scipy.stats import mannwhitneyu

ROOT = Path(__file__).resolve().parents[1]


def load(folder):
    rows = []
    for f in sorted(glob.glob(str(ROOT / folder / "*.json"))):      # top level only (skips repro_check/)
        d = json.load(open(f))
        d["bc_weight"] = d.get("bc_weight", 1.0)
        rows.append(d)
    return rows


exp1a, exp1b = load("results/kaggle/heat1d_recipe"), load("results/kaggle/heat1d_weights")
lines = []


def out(s=""):
    print(s)
    lines.append(s)


def group(rows):
    g = defaultdict(list)
    for r in rows:
        g[(r["precision"], r["constraint"], r["bc_weight"])].append(r)
    return dict(sorted(g.items(), key=lambda kv: (kv[0][0], kv[0][1] == "soft", kv[0][2])))


def table(title, rows):
    out(f"\n### {title}\n")
    out("| precision | BC/IC | bc weight | n | L2 median [min, max] | wall-flux L2 | stored-energy L2 | "
        "L-BFGS its (median) | stopped before cap | min/run |")
    out("|---|---|---|---|---|---|---|---|---|---|")
    for (prec, con, w), rs in group(rows).items():
        g = lambda k: np.array([r["final"][k] for r in rs])
        its = np.array([r["lbfgs_iters_run"] for r in rs])
        mins = np.mean([(r["seconds_adam"] + r["seconds_lbfgs"]) / 60 for r in rs])
        out(f"| {prec} | {con} | {'-' if con == 'hard' else format(w, 'g')} | {len(rs)} | "
            f"{np.median(g('l2')):.2e} [{g('l2').min():.2e}, {g('l2').max():.2e}] | "
            f"{np.median(g('flux_l2')):.2e} | {np.median(g('energy_l2')):.2e} | {int(np.median(its))} | "
            f"{sum(r['lbfgs_stopped_early'] for r in rs)}/{len(rs)} | {mins:.1f} |")


out("## Experiment 1 summary (generated by analysis/summarize_heat1d.py)")
out(f"\nRuns found: 1a = {len(exp1a)} (unseeded initialization), 1b = {len(exp1b)} (seeded initialization).")
table("Experiment 1a: precision x BC/IC enforcement (independent runs; initialization not seeded)", exp1a)
table("Experiment 1b: float32, BC/IC loss weights vs exact enforcement (reproducible seeds 0-4)", exp1b)

# ---- pooled float32 replicates (same recipe, different initialization RNG stream) ----
out("\n### Pooled float32 replicates (1a + 1b, same recipe)\n")
out("| setting | n | L2 median [min, max] |")
out("|---|---|---|")
pooled = {}
for label, key in (("float32 soft, weight 1", ("float32", "soft", 1.0)), ("float32 hard", ("float32", "hard", 1.0))):
    vals = [r["final"]["l2"] for r in exp1a + exp1b if (r["precision"], r["constraint"], r["bc_weight"]) == key]
    pooled[label] = np.array(vals)
    out(f"| {label} | {len(vals)} | {np.median(vals):.2e} [{min(vals):.2e}, {max(vals):.2e}] |")

# ---- key comparisons inside 1b (same seeds, same code path) ----
out("\n### Hard constraints vs each soft weight (Experiment 1b, n = 5 vs 5)\n")
out("| comparison | ratio of medians (soft/hard) | worst hard / best soft | exact two-sided Mann-Whitney p |")
out("|---|---|---|---|")
g1b = group(exp1b)
hard = np.array([r["final"]["l2"] for r in g1b[("float32", "hard", 1.0)]])
for (prec, con, w), rs in g1b.items():
    if con != "soft":
        continue
    soft = np.array([r["final"]["l2"] for r in rs])
    p = mannwhitneyu(soft, hard, alternative="two-sided", method="exact").pvalue
    out(f"| soft w={w:g} vs hard | {np.median(soft) / np.median(hard):.1f}x | "
        f"{hard.max() / soft.min():.2f} | {p:.4f} |")
out("\nNote: with 5 vs 5 runs and completely separated ranges the smallest possible two-sided p is 0.0079; "
    "four comparisons were made, so treat it as a rank statement, not a precise probability.")

# ---- figure: every run as a point, median as a bar ----
cats = []
for label, rows, key in (
        ("f32 soft\nw=1", exp1b, ("float32", "soft", 1.0)), ("f32 soft\nw=10", exp1b, ("float32", "soft", 10.0)),
        ("f32 soft\nw=100", exp1b, ("float32", "soft", 100.0)), ("f32 soft\nw=1000", exp1b, ("float32", "soft", 1000.0)),
        ("f32 hard", exp1b, ("float32", "hard", 1.0)),
        ("f64 soft\nw=1 (1a)", exp1a, ("float64", "soft", 1.0)), ("f64 hard\n(1a)", exp1a, ("float64", "hard", 1.0))):
    v = [r["final"]["l2"] for r in rows if (r["precision"], r["constraint"], r["bc_weight"]) == key]
    if v:
        cats.append((label, np.array(v)))

rng = np.random.default_rng(0)
fig, ax = plt.subplots(figsize=(10, 5))
for i, (label, v) in enumerate(cats):
    ax.scatter(i + rng.uniform(-0.12, 0.12, len(v)), v, s=40, alpha=0.8, zorder=3)
    ax.hlines(np.median(v), i - 0.3, i + 0.3, colors="k", lw=2, zorder=4)
ax.set_yscale("log")
ax.set_xticks(range(len(cats)))
ax.set_xticklabels([c[0] for c in cats], fontsize=9)
ax.set_ylabel("final relative L2 error (whole space-time domain)")
ax.set_title("1D heat PINN: every run (dots) and median (bar); float32 = Experiment 1b, float64 = 1a")
ax.grid(True, which="both", axis="y", alpha=0.3)
fig.tight_layout()
(ROOT / "results" / "figures").mkdir(parents=True, exist_ok=True)
fig.savefig(ROOT / "results" / "figures" / "heat1d_recipe_l2.png", dpi=150)
(ROOT / "results" / "tables").mkdir(parents=True, exist_ok=True)
(ROOT / "results" / "tables" / "heat1d_experiments.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
print("\nSaved results/figures/heat1d_recipe_l2.png and results/tables/heat1d_experiments.md")
